// Builds src/lib/director-styles.ts from the owner's director style modules (kept unchanged in docs/prompt-engines/knowledge/original/director-craft/director_styles/).
// The text of each module is kept word for word. Only what points at files Eclipse does not carry is taken out: the front matter, the "配套参考" lines and the
// sentences that only say "see ../cinematic-language.md". Links to the other modules keep their label. Run: node scripts/build-director-styles.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { transform } from "./director-styles-transform.mjs";

const dir = "docs/prompt-engines/knowledge/original/director-craft/director_styles";
const files = readdirSync(dir).filter((f) => /^\d\d_.*\.md$/.test(f)).sort();
const out = {};
for (const f of files) out[f.replace(/^\d\d_/, "").replace(/\.md$/, "")] = transform(readFileSync(`${dir}/${f}`, "utf8"));
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
writeFileSync("src/lib/director-styles.ts", `// GENERATED by scripts/build-director-styles.mjs from the owner's director style modules (originals unchanged in docs/prompt-engines/knowledge/original/director-craft/director_styles/).
// Do not edit by hand: change the build rule or the originals and run the script. tests/unit/director-styles.test.ts keeps this equal to the originals.
export const DIRECTOR_STYLES: Record<string, string> = {\n${body}\n};\n`);
console.log(`${files.length} modules, ${Object.values(out).reduce((n, v) => n + v.length, 0)} characters`);
